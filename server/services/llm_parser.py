import os
import re
import json
import subprocess
from datetime import datetime, timedelta

MODEL_PATH = os.path.expanduser("~/pocketbrain/models/smollm2-360m-instruct.Q4_K_M.gguf")
LLAMA_CLI_PATH = os.path.expanduser("~/pocketbrain/llama.cpp/build/bin/llama-cli")

def get_llama_binary():
    for p in [LLAMA_CLI_PATH]:
        if os.path.exists(p) and os.access(p, os.X_OK):
            return p
    return None

def is_llm_available():
    binary = get_llama_binary()
    return binary is not None and os.path.exists(MODEL_PATH)

def _build_prompt(message):
    today_str = datetime.now().strftime('%Y-%m-%d')
    tomorrow_str = (datetime.now() + timedelta(days=1)).strftime('%Y-%m-%d')
    return ('Convert this user message to JSON.\n'
        'Example 1: "spent 80 on dosa" -> {"action":"expense","amount":80,"description":"dosa","category":"food"}\n'
        'Example 2: "remind me to call dad at 18:00" -> {"action":"reminder","title":"call dad","date":"' + today_str + '","time":"18:00"}\n'
        'Example 3: "bunked OS class" -> {"action":"attendance","subject":"OS","status":"bunked"}\n'
        'Example 4: "did 30 pushups" -> {"action":"habit","name":"exercise"}\n'
        'Now parse: "' + message + '" ->')

def extract_json(raw_text):
    if not raw_text:
        return None
    cleaned = re.sub(r'```json\s*', '', raw_text)
    cleaned = re.sub(r'```\s*', '', cleaned)
    candidates = re.findall(r'\{[^{}]*\}', cleaned)
    # Take the LAST JSON match (the one generated by the model for the actual message!)
    for c in reversed(candidates):
        try:
            data = json.loads(c)
            # Make sure it's not one of the static examples
            if 'action' in data and data.get('description') != 'dosa' and data.get('title') != 'call dad':
                if 'amount' in data:
                    try:
                        data['amount'] = float(data['amount'])
                    except (ValueError, TypeError):
                        pass
                return data
        except (json.JSONDecodeError, ValueError):
            continue
    # If not filtered, return the last candidate anyway
    if candidates:
        try:
            return json.loads(candidates[-1])
        except Exception:
            pass
    return None

def llm_parse(message):
    binary = get_llama_binary()
    if not binary or not os.path.exists(MODEL_PATH):
        return None
    prompt = _build_prompt(message)
    cmd = [binary, "-m", MODEL_PATH, "-p", prompt,
           "-n", "50", "-t", "4", "--temp", "0.1",
           "--single-turn", "--simple-io", "--no-display-prompt",
           "-c", "512"]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=45, stdin=subprocess.DEVNULL)
        output = (proc.stdout + "\n" + proc.stderr).strip()
        parsed = extract_json(output)
        if parsed:
            print("[LLM] success parsed:", parsed)
            return parsed
    except subprocess.TimeoutExpired:
        print("LLM timed out (45s)")
    except Exception as e:
        print("LLM error:", e)
    return None
